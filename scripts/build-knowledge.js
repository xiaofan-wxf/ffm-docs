// AUTO-RUN as prebuild: node scripts/build-knowledge.js
// Reads all docs/**/*.md (excluding internal/ and superpowers/) and generates
// src/lib/knowledgeBase.ts so the chatbot always reflects the latest docs content.

const fs = require('fs');
const path = require('path');

const DOCS_DIR = path.join(__dirname, '../docs');
const OUTPUT = path.join(__dirname, '../src/lib/knowledgeBase.ts');
const SKIP_DIRS = new Set(['internal', 'superpowers']);

function collectMdFiles(dir, base) {
  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const rel = path.relative(base, full).split(path.sep)[0];
      if (!SKIP_DIRS.has(rel)) results.push(...collectMdFiles(full, base));
    } else if (entry.name.endsWith('.md')) {
      results.push(full);
    }
  }
  return results;
}

function process(filePath) {
  let text = fs.readFileSync(filePath, 'utf-8');
  // strip frontmatter
  text = text.replace(/^---[\s\S]*?---\n?/, '');
  // strip docusaurus callout markers (:::caution, :::info, etc.) but keep body
  text = text.replace(/:::[a-z]+[^\n]*\n/g, '').replace(/:::\n?/g, '');
  return text.trim();
}

function build() {
  const files = collectMdFiles(DOCS_DIR, DOCS_DIR).sort();
  const parts = [];

  for (const f of files) {
    const content = process(f);
    if (content) parts.push(content);
  }

  const kb = parts.join('\n\n---\n\n');
  // Escape backticks and template literal interpolation markers
  const escaped = kb.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

  const out = `// AUTO-GENERATED by scripts/build-knowledge.js — do not edit by hand.
export const KNOWLEDGE_BASE = \`
${escaped}
\`.trim();

export function buildSystemPrompt(): string {
  return \`你是 FFM（Flash Fulfillment）的智能客服助手。
请检测用户提问的语言，并用相同语言回答（中文问题用中文，英文问题用英文，泰文问题用泰文）。
只根据以下知识库内容回答问题。如果问题超出知识库范围，请告知用户联系商务人员。
不要编造知识库中没有的信息。
回答操作步骤时，如果知识库中有对应截图引用，请在回答中用 Markdown 图片语法包含截图，例如：![说明](/img/img_001.png)。

\${KNOWLEDGE_BASE}\`;
}
`;

  fs.writeFileSync(OUTPUT, out, 'utf-8');
  const kbKB = Math.round(kb.length / 1024);
  console.log(`[build-knowledge] ${files.length} docs → ${kbKB} KB → ${OUTPUT}`);
}

build();
